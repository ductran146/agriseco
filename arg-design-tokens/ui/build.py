"""Build ARG UI.

  python3 ui/build.py

Reads ui/components/<name>/{<name>.css, .js, .html, .md} and writes ui/dist/:
  arg-ui.css          all component CSS, concatenated (needs arg-tokens.css)
  arg-ui.js           core + icon sprite + all component modules
  arg-tokens.css      copy of ../arg-tokens.css
  arg-ui-viewer.html  ONE file: tokens + font + the two files above + every component's example and doc
  build-report.json   results of the build checks
The viewer holds no component CSS/JS of its own; it only lays the real files out for inspection.
"""
import base64, html, json, re, sys
from pathlib import Path

UI = Path(__file__).resolve().parent
ROOT = UI.parent
DIST = UI / 'dist'
DIST.mkdir(exist_ok=True)
cfg = json.loads((UI / 'components.json').read_text(encoding='utf-8'))
comps = cfg['components']
read = lambda p: Path(p).read_text(encoding='utf-8')

# ---------- icons ----------
icons, VIEWBOX = {}, {}
for f in sorted((UI / 'icons').glob('*.svg')):
    svg = read(f)
    inner = re.search(r'<svg[^>]*>(.*)</svg>', svg, re.S).group(1)
    vb = re.search(r'viewBox="([^"]+)"', svg).group(1)
    icons[f.stem] = re.sub(r'\s+', ' ', inner).strip()
    VIEWBOX[f.stem] = vb
GRADS = (('up', '--arg-trading-up-light-increase'), ('down', '--arg-trading-down-light-increase'), ('ref', '--arg-trading-flat-flat'))
sprite = ('<svg width="0" height="0" style="position:absolute" aria-hidden="true"><defs>'
          + ''.join(f'<symbol id="i-{n}" viewBox="{VIEWBOX[n]}">{b}</symbol>' for n, b in icons.items())
          + ''.join(f'<linearGradient id="arg-grad-{k}" x1="0" y1="0" x2="0" y2="1"><stop offset="0" style="stop-color:var({v})"/>'
                    f'<stop offset="1" style="stop-color:var({v});stop-opacity:0"/></linearGradient>' for k, v in GRADS)
          + '</defs></svg>')

# ---------- css ----------
css_parts = []
for rel in cfg['css']:
    css_parts.append(read(UI / rel).rstrip() + '\n')
css = '/* ARG UI components. Generated by ui/build.py from ui/components/*. Needs arg-tokens.css. */\n\n' + '\n'.join(css_parts)
(DIST / 'arg-ui.css').write_text(css, encoding='utf-8')

# ---------- js ----------
js_order = ['base/core.js'] + [f'components/{n}/{n}.js' for n in
                               ['icon', 'alert', 'button', 'input', 'dropdown', 'tabs', 'accordion', 'carousel', 'modal', 'notification', 'progress', 'reco', 'screen', 'chart', 'appbar', 'side', 'stepper', 'account', 'events', 'listbar', 'acctsel', 'ordermodal', 'selectsheet', 'orderbook', 'orderdetail', 'book', 'suggest', 'fab', 'keyboard', 'datepicker']]
js_parts = []
for rel in js_order:
    src = read(UI / rel)
    if rel.endswith('icon.js'):
        src = src.replace("'__ARG_ICON_SPRITE__'", json.dumps(sprite))
    js_parts.append(f'/* --- {rel} --- */\n' + src.rstrip() + '\n')
js = '/* ARG UI behaviour. Generated by ui/build.py from ui/components/*. */\n' + '\n'.join(js_parts)
(DIST / 'arg-ui.js').write_text(js, encoding='utf-8')

tokens_css = read(ROOT / 'arg-tokens.css')
(DIST / 'arg-tokens.css').write_text(tokens_css, encoding='utf-8')

# ---------- fragments ----------
logo_b64 = base64.b64encode((UI / 'viewer/assets/logo-agriseco.svg').read_bytes()).decode()


def ph_img(w, h, label):
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {w} {h}"><defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="0">'
           f'<stop offset="0" stop-color="#EA5B2F"/><stop offset="1" stop-color="#F33A44"/></linearGradient></defs><rect width="{w}" height="{h}" fill="url(#g)"/>'
           f'<path d="M0 {h*.78:.0f} L{w*.28:.0f} {h*.5:.0f} L{w*.48:.0f} {h*.66:.0f} L{w*.72:.0f} {h*.3:.0f} L{w} {h*.58:.0f} V{h} H0Z" fill="#fff" fill-opacity=".28"/>'
           f'<text x="{w/2:.0f}" y="{h*.2:.0f}" text-anchor="middle" font-family="sans-serif" font-size="{h//9}" fill="#fff" font-weight="700">{label}</text></svg>')
    return 'data:image/svg+xml;base64,' + base64.b64encode(svg.encode()).decode()


def macro_sw(m):
    cells = []
    for item in m.group(1).split(';'):
        name, var = item.split('|')
        cells.append(f'<div class="sw"><div class="chip" style="background:var({var})"></div><b>{name}</b><span class="px">{var}</span></div>')
    return ''.join(cells)


def macro_imgrow(_):
    out = []
    for i, (cls, cap) in enumerate([('arg-img', 'Mặc định'), ('arg-img arg-img--rounded', 'Bo góc'), ('arg-img arg-img--circle', 'Tròn'), ('arg-img arg-img--thumb', 'Viền')]):
        w = 120 if i == 2 else 160
        out.append(f'<figure class="arg-figure"><img class="{cls}" width="{w}" height="120" src="{ph_img(w, 120, "ARG")}" alt="Ảnh minh hoạ {cap.lower()}"><figcaption>{cap}</figcaption></figure>')
    return ''.join(out)


def macro_icons(_):
    return ''.join(f'<div class="icon-cell"><i data-arg-icon="{n}"></i><span>{n}</span></div>' for n in icons)


def md_to_html(md):
    def inline(s):
        s = html.escape(s, quote=False)
        s = re.sub(r'`([^`]+)`', r'<code>\1</code>', s)
        return re.sub(r'\*\*([^*]+)\*\*', r'<b>\1</b>', s)
    out, table, bullets = [], [], []

    def flush():
        nonlocal table, bullets
        if table:
            head, body = table[0], table[2:]
            out.append('<div class="tbl-scroll"><table><thead><tr>' + ''.join(f'<th scope="col">{inline(c)}</th>' for c in head) + '</tr></thead><tbody>' +
                       ''.join('<tr>' + ''.join(f'<td>{inline(c)}</td>' for c in r) + '</tr>' for r in body) + '</tbody></table></div>')
            table = []
        if bullets:
            out.append('<ul>' + ''.join(f'<li>{inline(b)}</li>' for b in bullets) + '</ul>')
            bullets = []
    for line in md.splitlines():
        if line.startswith('|'):
            table.append([c.strip() for c in line.strip().strip('|').split('|')])
            continue
        if line.startswith('- '):
            bullets.append(line[2:])
            continue
        flush()
        if line.startswith('## '):
            out.append(f'<h3>{inline(line[3:])}</h3>')
        elif line.strip():
            out.append(f'<p>{inline(line)}</p>')
    flush()
    return '\n'.join(out)


sections, nav = [], []
for c in comps:
    n = c['id']
    frag = read(UI / f'components/{n}/{n}.html').strip()
    md_path = UI / f'components/{n}/{n}.md'
    if md_path.exists():
        spec = ('<details class="spec"><summary>Tài liệu: class, trạng thái, JS</summary><div class="spec__body">' + md_to_html(read(md_path)) + '</div></details>')
        i = frag.rindex('</section>')
        frag = frag[:i] + spec + '\n      ' + frag[i:]
    frag = re.sub(r'\{\{SW:(.*?)\}\}', macro_sw, frag)
    frag = frag.replace('{{IMGROW}}', macro_imgrow(None)).replace('{{ICONS}}', macro_icons(None)).replace('__LOGO__', logo_b64)
    sections.append('      ' + frag)
    nav.append(f'        <a href="#{n}">{html.escape(c["title"])}</a>')
sections_html = '\n\n'.join(sections)

# ---------- build checks ----------
checks = []
defined = set(re.findall(r'(--arg-[a-z0-9-]+)\s*:', tokens_css + css))  # token + biến chuẩn khai báo trong base.css
used = set(re.findall(r'var\((--arg-[a-z0-9-]+)', css + js + sections_html))
missing_vars = sorted(used - defined)
checks.append({'ok': not missing_vars, 'name': 'Token CSS được dùng đều tồn tại', 'detail': f'{len(used)} biến dùng, thiếu: {", ".join(missing_vars) or "không"}'})

css_classes = set(re.findall(r'\.((?:arg-|i(?:--|\b))[A-Za-z0-9_-]*)', css))
html_classes = set()
for m in re.finditer(r'class="([^"]*)"', sections_html):
    html_classes.update(c for c in m.group(1).split() if c.startswith('arg-') or c == 'i' or c.startswith('i--'))
# state / JS-set classes are legitimate without a standalone rule
ignore = {'arg-ui'}
missing_cls = sorted(c for c in html_classes - css_classes - ignore)
checks.append({'ok': not missing_cls, 'name': 'Class trong ví dụ đều có CSS', 'detail': f'{len(html_classes)} class dùng, thiếu: {", ".join(missing_cls) or "không"}'})

need_icons = set(re.findall(r'data-arg-icon="([a-z0-9-]+)"', sections_html))
need_icons |= set(re.findall(r"ARG\.icon\(\s*(?:[a-z]+ \? )?'([a-z0-9-]+)'(?: : '([a-z0-9-]+)')?", js and ''.join(js_parts)) and
                  {x for t in re.findall(r"ARG\.icon\(\s*(?:[a-z]+ \? )?'([a-z0-9-]+)'(?: : '([a-z0-9-]+)')?", ''.join(js_parts)) for x in t if x})
need_icons |= set(re.findall(r"\['([a-z0-9-]+)', 'var\(", ''.join(js_parts)))
missing_icons = sorted(need_icons - set(icons))
checks.append({'ok': not missing_icons, 'name': 'Icon Solar được dùng đều có trong sprite', 'detail': f'{len(need_icons)} icon dùng / {len(icons)} trong sprite, thiếu: {", ".join(missing_icons) or "không"}'})

no_doc = [c['id'] for c in comps if not (UI / f'components/{c["id"]}/{c["id"]}.md').exists()]
checks.append({'ok': not no_doc, 'name': 'Mỗi component có ví dụ HTML và tài liệu', 'detail': f'{len(comps)} component, thiếu tài liệu: {", ".join(no_doc) or "không"}'})

fields = {'--arg-border-height-size-height-normal', '--arg-border-height-size-height-xl', '--arg-border-height-size-height-xxl', '--arg-border-height-size-height-small'}
checks.append({'ok': fields <= defined, 'name': 'Token chiều cao điều khiển (32 / 40 / 44 / 48)', 'detail': 'height-small, height-normal, height-xl, height-xxl'})
gradient_ok = '--arg-gradient-primary-button' in defined
checks.append({'ok': gradient_ok, 'name': 'Gradient nút chính theo header web Agriseco', 'detail': next((l.strip() for l in tokens_css.splitlines() if '--arg-gradient-primary-button:' in l), 'thiếu')})
(DIST / 'build-report.json').write_text(json.dumps({'checks': checks}, ensure_ascii=False, indent=2), encoding='utf-8')

# ---------- viewer: one file ----------
lines = tokens_css.splitlines()


def block(start):
    i = next(n for n, l in enumerate(lines) if l.startswith(start))
    j = next(n for n in range(i, len(lines)) if lines[n] == '}')
    return i, j


pi, pj = block(':root {')
ei, ej = block(':root, [data-theme] {')
li, lj = block(':root, [data-theme="light"] {')
di, dj = block('[data-theme="dark"] {')
body = lambda i, j: '\n'.join(l for l in lines[i + 1:j] if 'color-scheme' not in l)
light, dark = body(li, lj), body(di, dj)
tokens_viewer = '\n'.join([
    '\n'.join(lines[pi:pj + 1]),
    ':root, .app {', body(ei, ej), '}',
    ':root {', light, '}',
    '@media (prefers-color-scheme: dark) { :root:not([data-theme="light"]) {', dark, '  color-scheme: dark;', '} }',
    ':root[data-theme="dark"] {', dark, '  color-scheme: dark;', '}',
    '.app[data-mode="light"] {', '  color-scheme: light;', light, '}',
    '.app[data-mode="dark"] {', '  color-scheme: dark;', dark, '}',
])

page = read(UI / 'viewer/shell.html')
repl = {
    '{{FONT}}': base64.b64encode((UI / 'viewer/fonts/PretendardVariable.woff2').read_bytes()).decode(),
    '{{LOGO}}': logo_b64,
    '{{TOKENS}}': tokens_viewer,
    '{{CSS}}': css,
    '{{SHELL_CSS}}': read(UI / 'viewer/shell.css'),
    '{{NAV}}': '\n'.join(nav),
    '{{SECTIONS}}': sections_html,
    '{{REPORT}}': json.dumps({'checks': checks}, ensure_ascii=False).replace('</', '<\\/'),
    '{{JS}}': js.replace('</script', '<\\/script'),
    '{{SHELL_JS}}': read(UI / 'viewer/shell.js'),
}
for k, v in repl.items():
    page = page.replace(k, v)
left = re.findall(r'\{\{[A-Z_]+\}\}', page)
assert not left, left
(DIST / 'arg-ui-viewer.html').write_text(page, encoding='utf-8')

for c in checks:
    print(('OK   ' if c['ok'] else 'FAIL ') + c['name'] + ' | ' + c['detail'])
print(f'dist/arg-ui.css {len(css)//1024} KB · dist/arg-ui.js {len(js)//1024} KB · viewer {len(page)/1e6:.2f} MB')
sys.exit(0 if all(c['ok'] for c in checks) else 1)
